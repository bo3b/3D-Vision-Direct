////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class ShutterGlasses
{
public:
    ShutterGlasses() :
        leftEye(true)
    {
    }

    void ToggleEyes()
    {
        leftEye = !leftEye;
    }

    bool IsLeftEye() const
    {
        return leftEye;
    }

    void SetLeftEye()
    {
        leftEye = true;
    }

    void SetRightEye()
    {
        leftEye = false;
    }

private:
    bool leftEye;
};

