#pragma once

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class ShutterGlasses
{
public:
    ShutterGlasses() :
        leftEye(true)
    {
    }

    void toggleEyes()
    {
        leftEye = !leftEye;
    }

    bool isLeftEye() const
    {
        return leftEye;
    }

    void setLeftEye()
    {
        leftEye = true;
    }

    void setRightEye()
    {
        leftEye = false;
    }

private:
    bool leftEye;
};

